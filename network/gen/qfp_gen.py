def make_orgs(n_orgs, n_peers):
    """The organisations of an O x P network, in the order of the live configtx.yaml."""
    if n_orgs < 1 or n_peers < n_orgs or n_peers % n_orgs:
        raise SystemExit("peers must be a multiple of orgs, and at least one per organisation")
    per = n_peers // n_orgs
    keys = ["general"] if n_orgs == 1 else ["government", "general"] + ["org%d" % i for i in range(3, n_orgs + 1)]
    orgs, idx = [], 0
    for key in keys:
        if key == "government":
            base, ca_port, ca_ops = 27051, 27054, 37054
        elif key == "general":
            base, ca_port, ca_ops = 29051, 28054, 38054
        else:
            n = int(key[3:])
            base, ca_port, ca_ops = 31051 + (n - 3) * 1000, 31054 + (n - 3) * 1000, 41054 + (n - 3)
        name = key.capitalize()
        domain = key + ".uae.com"
        org = {
            "key": key, "name": name, "domain": domain, "msp": name + "MSP",
            "ca_name": name + "CA", "ca_host": "ca." + domain, "ca_port": ca_port, "ca_ops": ca_ops,
            "cc_host": "chaincode-" + key,
            "dir": "crypto-material/peerOrganizations/" + domain,
            "peers": [],
        }
        for j in range(per):
            host = "peer%d.%s" % (j, domain)
            port = base + 10 * j
            org["peers"].append({
                "host": host, "port": port, "cc_port": port + 1, "ops": 39444 + idx,
                "dir": "%s/peers/%s" % (org["dir"], host),
            })
            idx += 1
        orgs.append(org)
    return orgs


def endorsements(n_orgs):
    """Endorsements a MAJORITY policy needs."""
    return n_orgs // 2 + 1


