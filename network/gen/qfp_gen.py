#!/usr/bin/env python3
"""qfp_gen.py: writes every file of one study network into a folder.

A network is described by four things:
  --orgs O        number of peer organisations (1, 2, 4, 8)
  --peers P       total number of peers (P/O per organisation)
  --identity X    ecdsa | mldsa44   (key algorithm of every Fabric identity)
  --blocks B      study (100 tx / 16 MB / 2 s) | live (10 tx / 512 KB / 2 s)

The output folder has the layout of QChain's qchain-network repository
(config/, fabric-ca/<org>/, scripts/), plus topology.json (the containers,
read by scripts/qfp.py) and client.json (read by the load generator).

The files are made from the verbatim copies in network/live (see
docs/live-differences.md for every difference). For the live case
(2 organisations, 1 peer each, mldsa44, live blocks) the generated
configtx.yaml, crypto-config.yaml and CA configurations are the live files
(comments aside): `qfp_gen.py --selfcheck` verifies this.

Standard library only; runs with the Python 3.9 of macOS.
"""

