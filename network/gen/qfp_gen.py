def sh_crypto(orgs):
    ids = ["$ORD/orderers/" + ORD_HOST, "$ORD/users/Admin@" + ORD_DOMAIN]
    for o in orgs:
        d = "$CM/peerOrganizations/" + o["domain"]
        ids += ["%s/peers/%s" % (d, p["host"]) for p in o["peers"]]
        ids.append("%s/users/Admin@%s" % (d, o["domain"]))
        if o["key"] == "government":
            ids.append("%s/users/issuer1@%s" % (d, o["domain"]))
        if o["key"] == "general":
            ids.append("%s/users/plain1@%s" % (d, o["domain"]))
    cli = "\n".join("mkcli admin-%s \"$CM/peerOrganizations/%s/users/Admin@%s\"" % (o["key"], o["domain"], o["domain"])
                    for o in orgs)
    keys = " ".join(o["key"] for o in orgs)
    return """#!/bin/bash
# Generated by network/gen/qfp_gen.py from the live scripts/generate-crypto-pqc.sh:
#   1. cryptogen -> crypto-material/   2. pqc-keystore copies   3. peer CLI configs
#   4./5. per-organisation CA bootstrap (cryptogen CA cert + key) and ECDSA CA server TLS.
set -euo pipefail
. "$(dirname "$0")/env.sh"
[ -e "$CM" ] && die "$CM already exists"
umask 077
echo "=== 1. cryptogen -> crypto-material/ ==="
cryptogen generate --config="$NET/config/crypto-config.yaml" --output="$CM" > /dev/null

echo "=== 2. pqc-keystore copies ==="
ORD=$CM/ordererOrganizations/%(od)s
n=0
for d in %(ids)s; do
  [ -f "$d/msp/keystore/priv_sk" ] || die "no msp/keystore/priv_sk in ${d#$NET/}"
  mkdir -p "$d/pqc-keystore"
  cp -p "$d/msp/keystore/priv_sk" "$d/pqc-keystore/priv_sk"
  cmp -s "$d/msp/keystore/priv_sk" "$d/pqc-keystore/priv_sk" || die "key store copy differs: ${d#$NET/}"
  n=$((n + 1))
done
echo "  $n key store copies"

echo "=== 3. peer CLI configs ==="
mkcli() { # name identity-dir
  local c=$CM/cli-config/$1
  mkdir -p "$c/production"
  sed -e "s#^\\(\\s*KeyStorePath:\\).*#\\1 $2/pqc-keystore#" -e "s#^\\(\\s*fileSystemPath:\\).*#\\1 $c/production#" \\
      "$NET/config/core.yaml" > "$c/core.yaml"
  [ "$(grep -c "KeyStorePath: $2/pqc-keystore" "$c/core.yaml")" = 1 ] || die "cli-config/$1: KeyStorePath not set exactly once"
}
%(cli)s

echo "=== 4./5. CA bootstrap and ECDSA CA server TLS ==="
for o in %(keys)s; do
  src=$CM/peerOrganizations/$o.uae.com/ca
  dst=$NET/fabric-ca/$o
  mkdir -p "$dst/cafiles" "$dst/tls"
  cp -p "$src/ca.$o.uae.com-cert.pem" "$dst/cafiles/ca.$o.uae.com-cert.pem"
  cp -p "$src/priv_sk" "$dst/cafiles/priv_sk"
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -sha256 -days 365 -noenc \\
    -keyout "$dst/tls/tls-key.pem" -out "$dst/tls/tls-cert.pem" -subj "/CN=ca.$o.uae.com" \\
    -addext "subjectAltName=DNS:ca.$o.uae.com,DNS:localhost,IP:127.0.0.1" \\
    -addext "keyUsage=critical,digitalSignature" -addext "extendedKeyUsage=serverAuth" 2> /dev/null
done
echo "crypto done"
""" % dict(od=ORD_DOMAIN, ids=" \\\n         ".join(ids), cli=cli, keys=keys)


def sh_channel(orgs):
    joins = "\n".join("( %s; echo \"  join %s\"; peer channel join -b \"$BLOCK\" )" % (ctx(o, p), p["host"])
                      for o in orgs for p in o["peers"])
    heights = "\n".join("( %s; echo \"  %s: $(peer channel getinfo -c \"$CHANNEL_NAME\" 2>&1 | grep -o '\"height\":[0-9]*')\" )"
                        % (ctx(o, p), p["host"]) for o in orgs for p in o["peers"])
    return """#!/bin/bash
# Generated by network/gen/qfp_gen.py from the live scripts/create-channel-pqc.sh:
# genesis block, the orderer joins, every peer joins.
set -euo pipefail
. "$(dirname "$0")/env.sh"
BLOCK=$NET/channel-artifacts/$CHANNEL_NAME.block
[ -e "$BLOCK" ] && die "$BLOCK already exists"
mkdir -p "$NET/channel-artifacts"

echo "=== genesis block ($CHANNEL_NAME) ==="
FABRIC_CFG_PATH="$NET/config" configtxgen -profile TwoOrgsChannel -outputBlock "$BLOCK" -channelID "$CHANNEL_NAME"

echo "=== orderer0 joins $CHANNEL_NAME ==="
OA=$CM/ordererOrganizations/%(od)s/users/Admin@%(od)s/tls
osnadmin channel join --channelID "$CHANNEL_NAME" --config-block "$BLOCK" -o "$ORDERER_ADMIN_ADDRESS" \\
  --ca-file "$ORDERER_TLSCA" --client-cert "$OA/client.crt" --client-key "$OA/client.key"
osnadmin channel list -o "$ORDERER_ADMIN_ADDRESS" \\
  --ca-file "$ORDERER_TLSCA" --client-cert "$OA/client.crt" --client-key "$OA/client.key"

echo "=== peers join $CHANNEL_NAME ==="
%(joins)s
sleep 3
%(heights)s
echo "channel done"
""" % dict(od=ORD_DOMAIN, joins=joins, heights=heights)


