def generate(n_orgs, n_peers, identity, blocks):
    """Returns {relative path: text} for one network."""
    if identity not in ("ecdsa", "mldsa44") or blocks not in BLOCKS:
        raise SystemExit("identity must be ecdsa or mldsa44; blocks must be study or live")
    orgs = make_orgs(n_orgs, n_peers)
    files = {
        "config/crypto-config.yaml": crypto_config(orgs, identity),
        "config/configtx.yaml": configtx(orgs, blocks),
        "config/core.yaml": node_config("core.yaml", identity),
        "config/orderer.yaml": node_config("orderer.yaml", identity),
        "scripts/env.sh": sh_env(orgs),
        "scripts/01-crypto.sh": sh_crypto(orgs),
        "scripts/02-channel.sh": sh_channel(orgs),
        "scripts/03-enroll.sh": sh_enroll(orgs, identity),
        "scripts/04-install.sh": sh_install(orgs),
        "scripts/05-commit.sh": sh_commit(orgs),
        "topology.json": json.dumps(topology(orgs, n_orgs, n_peers, identity, blocks), indent=1) + "\n",
        "client.json": json.dumps(client_view(orgs, n_orgs, n_peers, identity, blocks), indent=1) + "\n",
        # mount points inside the read-only config folder (see topology())
        "config/msp/.mountpoint": "", "config/tls/.mountpoint": "", "config/pqc-keystore/.mountpoint": "",
    }
    for o in orgs:
        files["fabric-ca/%s/fabric-ca-server-config.yaml" % o["key"]] = ca_config(o, identity)
    return files


def write(files, out):
    if os.path.exists(out) and os.listdir(out):
        raise SystemExit("%s exists and is not empty" % out)
    for rel, text in sorted(files.items()):
        path = os.path.join(out, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        if rel.endswith(".sh"):
            os.chmod(path, 0o755)


def canon(text):
    """A YAML text without comments, trailing blanks and empty lines."""
    lines = []
    for line in text.splitlines():
        line = re.sub(r"\s+#.*$", "", line).rstrip()
        if line and not line.lstrip().startswith("#"):
            lines.append(line)
    return lines


def selfcheck():
    """The live case must reproduce the live files; every topology must generate."""
    bad = 0
    live = generate(2, 2, "mldsa44", "live")
    pairs = [
        ("config/crypto-config.yaml", "config/crypto-config.yaml"),
        ("config/configtx.yaml", "config/configtx.yaml"),
        ("fabric-ca/general/fabric-ca-server-config.yaml", "fabric-ca/general/fabric-ca-server-config.yaml"),
        ("fabric-ca/government/fabric-ca-server-config.yaml", "fabric-ca/government/fabric-ca-server-config.yaml"),
    ]
    for gen_rel, live_rel in pairs:
        a, b = canon(live[gen_rel]), canon(read_live(live_rel))
        if a == b:
            print("same as live (comments aside): %s" % gen_rel)
        else:
            bad += 1
            print("DIFFERS from live: %s" % gen_rel)
            for i in range(max(len(a), len(b))):
                x = a[i] if i < len(a) else "<none>"
                y = b[i] if i < len(b) else "<none>"
                if x != y:
                    print("   generated: %s\n   live:      %s" % (x, y))
                    break
    for rel in ("config/core.yaml", "config/orderer.yaml"):
        if live[rel] == read_live(rel):
            print("byte-identical to live: %s" % rel)
        else:
            bad += 1
            print("DIFFERS from live: %s" % rel)
    # the live environment of the orderer and of a peer, from the live compose file
    compose = read_live("docker/docker-compose.yaml")
    topo = json.loads(live["topology.json"])
    for name in (ORD_HOST, "peer0.government.uae.com", "peer0.general.uae.com"):
        block = compose.split("\n  %s:\n" % name)[-1]     # the service, not the volume of that name
        block = block.split("\n    volumes:", 1)[0]
        want = dict(m.groups() for m in re.finditer(r"(?m)^\s+- ([A-Z_]+)=(.*)$", block))
        got = [c for c in topo["containers"] if c["name"] == name][0]["env"]
        if want == got:
            print("environment same as live compose: %s (%d variables)" % (name, len(got)))
        else:
            bad += 1
            keys = sorted(set(want) ^ set(got)) + sorted(k for k in set(want) & set(got) if want[k] != got[k])
            print("ENVIRONMENT DIFFERS for %s: %s" % (name, ", ".join(keys)))
    n = 0
    for o, p in ((1, 1), (1, 2), (1, 4), (1, 8), (2, 2), (2, 4), (2, 8), (4, 4), (4, 8), (8, 8)):
        for ident in ("ecdsa", "mldsa44"):
            for blocks in ("study", "live"):
                t = json.loads(generate(o, p, ident, blocks)["topology.json"])
                assert len(t["containers"]) == 1 + p + 2 * o, (o, p)
                names = [c["name"] for c in t["containers"]]
                assert len(names) == len(set(names))
                n += 1
    print("generated %d networks (10 topologies x 2 identities x 2 block profiles)" % n)
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--orgs", type=int)
    ap.add_argument("--peers", type=int)
    ap.add_argument("--identity", choices=["ecdsa", "mldsa44"])
    ap.add_argument("--blocks", choices=sorted(BLOCKS), default="study")
    ap.add_argument("--out")
    ap.add_argument("--selfcheck", action="store_true")
    a = ap.parse_args()
    if a.selfcheck:
        sys.exit(1 if selfcheck() else 0)
    if not (a.orgs and a.peers and a.identity and a.out):
        ap.error("--orgs, --peers, --identity and --out are required")
    write(generate(a.orgs, a.peers, a.identity, a.blocks), a.out)
    print(net_id(a.orgs, a.peers, a.identity, a.blocks))


if __name__ == "__main__":
    main()
