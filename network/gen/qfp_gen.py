def sh_install(orgs):
    body = ""
    for o in orgs:
        installs = "\n".join("( %s; echo \"  install on %s\"; peer lifecycle chaincode install \"$PKG/$CC_NAME.tar.gz\" )"
                             % (ctx(o, p), p["host"]) for p in o["peers"])
        body += """
echo "=== package for %(name)s (chaincode server %(cc)s:9998) ==="
PKG=$NET/chaincode-pkg/%(key)s
[ -e "$PKG" ] && die "$PKG already exists"
mkdir -p "$PKG"
printf '{"address":"%(cc)s:9998","dial_timeout":"10s","tls_required":false}\\n' > "$PKG/connection.json"
printf '{"type":"ccaas","label":"%%s"}\\n' "$CC_LABEL" > "$PKG/metadata.json"
tar -C "$PKG" -czf "$PKG/code.tar.gz" connection.json
tar -C "$PKG" -czf "$PKG/$CC_NAME.tar.gz" metadata.json code.tar.gz
( %(ctx)s; peer lifecycle chaincode calculatepackageid "$PKG/$CC_NAME.tar.gz" > "$PKG/package-id" )
echo "  package ID $(cat "$PKG/package-id")"
%(installs)s
""" % dict(name=o["name"], key=o["key"], cc=o["cc_host"], ctx=ctx(o, o["peers"][0]), installs=installs)
    return """#!/bin/bash
# Generated by network/gen/qfp_gen.py from the first half of the live scripts/deployCC-pqc.sh.
# Difference from live: one package (and one chaincode server) per organisation, so each
# organisation has its own package ID (chaincode-pkg/<org>/package-id).
set -euo pipefail
. "$(dirname "$0")/env.sh"
%s
echo "install done"
""" % body


