def ca_config(org, identity):
    """The live General CA configuration with the organisation's names and port."""
    t = read_live("fabric-ca/general/fabric-ca-server-config.yaml")
    t = t.replace("GeneralMSP", org["msp"]).replace("GeneralCA", org["ca_name"])
    t = t.replace("general.uae.com", org["domain"])
    t = t.replace("28054", str(org["ca_port"]))
    t, n = re.subn(r"(?m)^affiliations:\n  general:", "affiliations:\n  %s:" % org["key"], t)
    if n != 1:
        raise SystemExit("ca_config: affiliations block not found")
    if identity == "ecdsa":
        t, n1 = re.subn(r"(?m)^(  keyrequest:\n    algo: )mldsa44$", r"\1ecdsa\n    size: 256", t)
        t, n2 = re.subn(r"(?m)^bccsp:\n  default: PQC\n  pqc:\n    keystorepath: msp/keystore$",
                        "bccsp:\n  default: SW\n  sw:\n    hash: SHA2\n    security: 256\n"
                        "    filekeystore:\n      keystore: msp/keystore", t)
        if (n1, n2) != (1, 1):
            raise SystemExit("ca_config: ecdsa substitutions failed (%d, %d)" % (n1, n2))
    return t


def node_config(name, identity):
    """core.yaml / orderer.yaml: verbatim for mldsa44; provider SW for ecdsa (one line)."""
    t = read_live("config/" + name)
    if identity == "ecdsa":
        t, n = re.subn(r"(?m)^(\s+Default: )PQC$", r"\1SW", t)
        if n != 1:
            raise SystemExit("%s: expected exactly one 'Default: PQC', found %d" % (name, n))
    return t


def client_ca_cfg(identity):
    """The fabric-ca-client configuration body after `url:` and `tls:` (live: registerEnroll.sh)."""
    if identity == "mldsa44":
        return "csr:\n  keyrequest:\n    algo: mldsa44\n\nbccsp:\n  default: PQC\n"
    return ("csr:\n  keyrequest:\n    algo: ecdsa\n    size: 256\n\n"
            "bccsp:\n  default: SW\n  sw:\n    hash: SHA2\n    security: 256\n")


